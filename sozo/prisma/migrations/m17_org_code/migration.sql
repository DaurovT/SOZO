-- Бизнес-код организации.
--
-- Контур «Дом» опознаёт оператора кодом — «uk1», «bc1», — и этот код стоит в
-- адресах кабинета (`/operator/uk1/finance`) и в карточке объекта. CRM о такой
-- организации не знала вовсе: одна и та же компания существовала в системе
-- дважды и в разных видах, и оператору нельзя было выставить счёт средствами
-- CRM, потому что контрагента не существовало.
--
-- Код уникален в пределах арендатора: по нему адресуются снаружи, и два
-- оператора с одним кодом означали бы, что запрос попадает не туда.

ALTER TABLE organization ADD COLUMN IF NOT EXISTS code text;

CREATE UNIQUE INDEX IF NOT EXISTS organization_tenant_code_idx
  ON organization (tenant_id, code) WHERE code IS NOT NULL;
