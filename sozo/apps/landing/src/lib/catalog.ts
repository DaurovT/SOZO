/**
 * Прайс-лист приходит в верхнем регистре («САНТЕХНИКА»). Для показа приводим к
 * обычному виду, но в API всегда уходит исходная строка категории.
 */
export function displayCategory(category: string): string {
  const lower = category.toLocaleLowerCase('ru');
  return lower.charAt(0).toLocaleUpperCase('ru') + lower.slice(1);
}

