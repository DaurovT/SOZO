import { Injectable } from '@nestjs/common';

/**
 * Общая очередь записи в базу — одна на процесс.
 *
 * У каждого модуля была своя цепочка промисов, и внутри модуля порядок
 * соблюдался. Между модулями — нет: объект и наряд-допуск пишутся разными
 * репозиториями, наряд ссылается на объект внешним ключом, и транзакция
 * наряда успевала зафиксироваться раньше транзакции объекта. Получался отказ
 * по внешнему ключу на данных, которые в памяти совершенно согласованы.
 *
 * Проявлялось это редко и оттого дорого: «иногда одна потерянная запись»,
 * причём в разных модулях в разных прогонах.
 *
 * Одна очередь на процесс убирает весь класс таких гонок: записи идут в том
 * же порядке, в каком их назначили, а назначают их в порядке предметной
 * области — сначала объект, потом наряд на него. Цена — записи не идут
 * параллельно; при нынешних объёмах это доли секунды, а при других сюда
 * встанет очередь на несколько потоков с учётом зависимостей, а не
 * параллельность вслепую.
 */
@Injectable()
export class WriteQueue {
  private tail: Promise<void> = Promise.resolve();

  /**
   * Поставить запись в очередь. Ошибка гасится вызывающим: очередь не решает,
   * что делать с неудачей, — она решает только порядок.
   */
  add(work: () => Promise<void>): Promise<void> {
    this.tail = this.tail.then(work, work);
    return this.tail;
  }

  /** Дождаться, пока очередь опустеет. Нужно разовому переносу и тестам */
  drain(): Promise<void> {
    return this.tail;
  }
}
