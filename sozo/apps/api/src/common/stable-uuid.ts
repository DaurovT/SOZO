import { createHash } from 'node:crypto';

/**
 * Детерминированный UUID из произвольной строки.
 *
 * Нужен там, где ключ операции естественный и осмысленный
 * («order.closed:<id>», «мастер + момент»), а колонка в базе имеет тип
 * `uuid`. Случайный идентификатор ломает идемпотентность: повтор создаёт
 * новую операцию вместо того, чтобы попасть в прежнюю. Строка-склейка не
 * является UUID и роняет запись — причём в зеркале это падение гасится, и
 * данные тихо остаются только в памяти.
 *
 * Один и тот же вход всегда даёт один и тот же выход, поэтому дедупликация
 * работает и после рестарта. Версия 5 по форме (имя + хеш), но без
 * пространства имён: криптографической стойкости здесь не требуется, нужна
 * воспроизводимость.
 */
export function stableUuid(seed: string): string {
  const h = createHash('sha1').update(seed).digest('hex');
  return [h.slice(0, 8), h.slice(8, 12), `5${h.slice(13, 16)}`, `8${h.slice(17, 20)}`, h.slice(20, 32)].join('-');
}
