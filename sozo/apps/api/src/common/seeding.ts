/**
 * Разрешён ли посев демо-данных.
 *
 * Модули, работающие на базе, при пустой базе записывают в неё то, что
 * собрано в конструкторе: демо-мастеров, демо-организации, стартовый релиз
 * прайса. Для разработки это правильно — иначе чистая база бесполезна.
 *
 * Для разового переноса state.json в PostgreSQL — нет: демо легло бы в базу
 * первым, а поверх него — настоящие данные, и в системе оказались бы вперемешку
 * выдуманные и живые контрагенты. Отличить их потом можно только руками.
 *
 * Поэтому посев выключается переменной, а не «догадливостью»: инструмент
 * переноса заявляет намерение явно, а обычный запуск ничего не меняет.
 */
export function seedingAllowed(): boolean {
  return process.env.SOZO_NO_SEED !== '1';
}
