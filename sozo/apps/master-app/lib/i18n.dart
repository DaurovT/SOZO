/// Словарь приложения мастера: русский и узбекский (F-02, DEV-09 §1).
///
/// Своя мини-реализация вместо генератора ARB — как в приложении клиента:
/// зависимость от кодогенерации усложняет сборку, а выигрыша при одном
/// словаре нет.
///
/// Узбекская колонка заполнена целиком. Полупереведённый интерфейс хуже
/// честно русского: мастер на объекте не должен гадать, что значит строка,
/// которую забыли перевести. Латиница — на ней сегодня пишут в Узбекистане.
///
/// Ключ — `экран.смысл`. Новую строку добавляют сразу в обе колонки; тест
/// `test/i18n_test.dart` не даст забыть.
class L10n extends ChangeNotifier {
  static const _key = 'sozo_master_locale';
  String _code = 'ru';

  String get code => _code;
  bool get isUz => _code == 'uz';

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    _code = prefs.getString(_key) ?? 'ru';
    notifyListeners();
  }

  Future<void> set(String code) async {
    if (code != 'ru' && code != 'uz') return;
    _code = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_key, code);
    notifyListeners(); // язык применяется мгновенно, без перезапуска
  }

  /// Подстановка параметров: t('order.adres', {'p1': address})
  String t(String key, [Map<String, Object?>? args]) {
    var s = (_code == 'uz' ? _uz[key] : null) ?? _ru[key] ?? key;
    if (args != null) {
      args.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
    }
    return s;
  }

  /// Перевод значения, а не подписи.
  ///
  /// Категории дефектов и типы техники приходят из словаря сервера и уходят
  /// обратно в payload — подменять их переводом нельзя, сломается сверка на
  /// бэкенде. Переводим только то, что видит мастер; незнакомое значение
  /// показываем как есть, а не прячем.
  String value(String v) => _code == 'uz' ? (_values[v] ?? v) : v;
}

