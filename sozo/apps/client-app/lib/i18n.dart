/// Словарь приложения «Клиент» (DEV-08 §1, чек-лист §6 п.1).
///
/// Своя мини-реализация вместо генератора ARB: зависимость от кодогенерации
/// усложняет сборку, а выигрыша при одном словаре нет. Ключи — как в DEV-08:
/// `экран.элемент`. Отсутствующий ключ показывает русский вариант, а не пустоту.
///
/// Узбекская колонка заполнена целиком: полупереведённый интерфейс для
/// узбекоязычного клиента хуже, чем честно русский, поэтому переводили не
/// по мере надобности, а разом. Латиница — на ней сегодня пишут в Узбекистане.
///
/// Новую строку добавляют сразу в обе колонки. Если узбекского варианта нет,
/// экран покажет русский — это лучше пустоты, но считается недоделкой.
class L10n extends ChangeNotifier {
  static const _key = 'sozo_client_locale';
  String _code = 'ru';

  /// Языки приложения. Русский — язык-основа: на нём написаны ключи,
  /// и он же служит запасным вариантом, когда перевода нет.
  static const codes = ['ru', 'uz', 'en'];

  String get code => _code;
  bool get isUz => _code == 'uz';
  bool get isEn => _code == 'en';

  Future<void> load() async {
    final prefs = await SharedPreferences.getInstance();
    final saved = prefs.getString(_key);
    _code = codes.contains(saved) ? saved! : 'ru';
    notifyListeners();
  }

  Future<void> set(String code) async {
    if (!codes.contains(code) || code == _code) return;
    _code = code;
    final prefs = await SharedPreferences.getInstance();
    await prefs.setString(_key, code);
    notifyListeners(); // C-30: язык применяется мгновенно, без перезапуска
  }

  /// Словарь выбранного языка. Русского словаря нет отдельно — русский и есть
  /// значение по умолчанию, поэтому `_ru` стоит последним звеном в `t`.
  Map<String, String>? get _dict => switch (_code) {
        'uz' => _uz,
        'en' => _en,
        _ => null,
      };

  /// Подстановка параметров ICU-стиля: t('x', {'sum': '120 000 сум'})
  ///
  /// Пропущенный перевод отдаёт русскую строку, а не пустоту и не ключ:
  /// незнакомое слово на чужом языке человек хотя бы сможет узнать по виду,
  /// «c14.quickTitle» — нет.
  String t(String key, [Map<String, Object?>? args]) {
    var s = _dict?[key] ?? _ru[key] ?? key;
    if (args != null) {
      args.forEach((k, v) => s = s.replaceAll('{$k}', '${v ?? ''}'));
    }
    return s;
  }
}

